--!nonstrict
-- BuildKitCheck cases: BuildKit/Fx and BuildKit/Gameplay.

return function(T)
	local BK, P, O = T.BK, T.P, T.O
	local expect, near, vec, fails, hex = T.expect, T.expectNear, T.expectVec, T.expectError, T.hex
	local V3 = Vector3.new
	local Y = O.Y

	local function host(f, name)
		return BK.part(f, { Name = name or "Host", Size = V3(2, 2, 2), Position = O })
	end

	T.case("light", function(f)
		local part = host(f)
		local point = BK.light(part, "Point", { Color = P.AMBER_LAMP, Brightness = 0.8, Range = 14, Shadows = true })
		expect(point.ClassName == "PointLight" and point.Parent == part, "PointLight on the part")
		near(point.Brightness, 0.8, "Brightness")
		near(point.Range, 14, "Range")
		expect(point.Shadows == true and hex(point.Color) == hex(P.AMBER_LAMP), "Shadows and Color")

		-- Capture the clamp warning instead of printing it to Output.
		local captured = {}
		local realWarn = BK.warn
		BK.warn = function(message)
			table.insert(captured, message)
		end
		local spot = BK.light(part, "Spot", { Brightness = 3, Range = 80, Angle = 50, Face = Enum.NormalId.Bottom })
		BK.warn = realWarn
		expect(spot.ClassName == "SpotLight", "SpotLight")
		near(spot.Range, 60, "Range is clamped to the Roblox maximum of 60")
		expect(#captured == 1 and string.find(captured[1], "clamped") ~= nil, "the clamp is reported as a warning")
		near(spot.Angle, 50, "Angle")
		expect(spot.Face == Enum.NormalId.Bottom and spot.Shadows == false, "Face, and Shadows default to false")
		expect(hex(spot.Color) == hex(P.LIGHT_NEUTRAL), "default light color")

		local surface = BK.light(part, "Surface", { Name = "Strip", Face = Enum.NormalId.Bottom, Angle = 120, Color = "#FFF1DA", Enabled = false, Tags = { "OutpostLight" }, Attributes = { Zone = "Test" } })
		expect(surface.ClassName == "SurfaceLight" and surface.Name == "Strip", "SurfaceLight with a name")
		expect(surface.Enabled == false and surface:HasTag("OutpostLight") and surface:GetAttribute("Zone") == "Test", "Enabled, Tags, Attributes")

		fails(function()
			BK.light(part, "Laser", {})
		end, "unknown light kind")
		fails(function()
			BK.light(part, "Point", { Colour = P.AMBER })
		end, "unknown light key")
	end)

	T.case("sign screen floorText", function(f)
		local sign = BK.sign(f, "Sign", CFrame.new(O + V3(0, 10, 0)), Vector2.new(12, 2), "Pilot Quarters")
		vec(sign.Size, V3(12, 2, 0.1), "sign size")
		expect(hex(sign.Color) == hex(P.SLATE_DEEP) and not sign.CanCollide and not sign.CanQuery, "sign base")
		local gui = sign:FindFirstChildOfClass("SurfaceGui")
		expect(gui and gui.Face == Enum.NormalId.Front, "SurfaceGui on the Front face")
		expect(gui.SizingMode == Enum.SurfaceGuiSizingMode.PixelsPerStud and gui.PixelsPerStud == 50, "50 pixels per stud")
		near(gui.LightInfluence, 0.6, "painted signs use LightInfluence 0.6")
		local label = gui:FindFirstChildOfClass("TextLabel")
		expect(label.Text == "PILOT QUARTERS", "sign text is ALL CAPS")
		expect(hex(label.TextColor3) == hex(P.AMBER), "amber text")
		expect(label.FontFace.Family == Font.fromEnum(Enum.Font.Michroma).Family, "Michroma header font")
		expect(label.TextScaled and label.BackgroundTransparency == 1, "scaled text, no label background")

		local lit = BK.sign(f, "Lit", CFrame.new(O + V3(0, 14, 0)), Vector2.new(8, 1), "Medical", { light = true, textColor = P.SIGN_WHITE, bgColor = P.SLATE, font = Enum.Font.TitilliumWeb })
		local litGui = lit:FindFirstChildOfClass("SurfaceGui")
		near(litGui.LightInfluence, 0, "lit signs are self-lit")
		expect(lit:FindFirstChildOfClass("SurfaceLight") ~= nil, "lit signs carry a glow")
		expect(hex(lit.Color) == hex(P.SLATE) and hex(litGui:FindFirstChildOfClass("TextLabel").TextColor3) == hex(P.SIGN_WHITE), "white on SLATE")

		local screen = BK.screen(f, "Screen", CFrame.new(O + V3(0, 18, 0)), Vector2.new(4.6, 1.6), { text = "Status nominal" })
		expect(screen.Material == Enum.Material.Neon and hex(screen.Color) == "1b2a33", "Neon screen base")
		near(screen.Transparency, 0.3, "screen transparency")
		local screenGui = screen:FindFirstChildOfClass("SurfaceGui")
		near(screenGui.LightInfluence, 0, "screens are self-lit")
		local screenLabel = screenGui:FindFirstChildOfClass("TextLabel")
		expect(screenLabel.Text == "Status nominal", "screen text keeps its case")
		expect(screenLabel.FontFace.Family == Font.fromEnum(Enum.Font.RobotoMono).Family, "mono font on screens")

		local text = BK.floorText(f, "FloorText", O + V3(0, 0, 30), Vector2.new(10, 2), "Pad A")
		expect(text.CFrame.LookVector:Dot(Vector3.yAxis) > 0.999, "floor text faces up")
		expect(text.CFrame.YVector:Dot(-Vector3.zAxis) > 0.999, "the top of the text points north (-Z)")
		near(text.Transparency, 1, "floor text has no background")
		local _, textHi = T.bounds(text)
		near(textHi.Y, Y + 0.05, "floor text sits 0.05 above the floor")
		local floorLabel = text:FindFirstChildOfClass("SurfaceGui"):FindFirstChildOfClass("TextLabel")
		expect(floorLabel.Text == "PAD A" and hex(floorLabel.TextColor3) == hex(P.HAZARD_YELLOW), "yellow painted text")
		near(floorLabel.TextTransparency, 0.15, "painted text transparency")
	end)

	T.case("emitter presets", function(f)
		local part = host(f)
		for _, name in ipairs(BK.emitterPresets) do
			local emitter = BK.emitter(part, name)
			expect(emitter.ClassName == "ParticleEmitter" and emitter.Name == name and emitter:GetAttribute("Preset") == name, "preset " .. name)
		end

		local sparks = part:FindFirstChild("Sparks")
		expect(sparks.Texture == "rbxasset://textures/particles/sparkles_main.dds", "Sparks texture")
		expect(hex(sparks.Color.Keypoints[1].Value) == "ffd38a" and hex(sparks.Color.Keypoints[2].Value) == "e07a1f", "Sparks color")
		near(sparks.Size.Keypoints[1].Value, 0.25, "Sparks size start")
		near(sparks.Size.Keypoints[2].Value, 0, "Sparks size end")
		near(sparks.Lifetime.Min, 0.3, "Sparks lifetime min")
		near(sparks.Lifetime.Max, 0.6, "Sparks lifetime max")
		near(sparks.Speed.Min, 15, "Sparks speed min")
		near(sparks.Speed.Max, 30, "Sparks speed max")
		expect(sparks.SpreadAngle == Vector2.new(60, 60) and sparks.Acceleration == V3(0, -60, 0), "Sparks spread and gravity")
		near(sparks.LightEmission, 1, "Sparks LightEmission")
		expect(sparks.Enabled == false and sparks:GetAttribute("EmitCount") == 25, "Sparks is a 25-particle burst")

		local smoke = part:FindFirstChild("Smoke")
		expect(smoke.Texture == "rbxasset://textures/particles/smoke_main.dds" and hex(smoke.Color.Keypoints[1].Value) == "3a3d42", "Smoke texture and color")
		near(smoke.Rate, 12, "Smoke rate")
		near(smoke.Size.Keypoints[1].Value, 3, "Smoke size start")
		near(smoke.Size.Keypoints[2].Value, 8, "Smoke size end")
		near(smoke.Transparency.Keypoints[1].Value, 0.4, "Smoke transparency start")
		near(smoke.Transparency.Keypoints[2].Value, 1, "Smoke transparency end")
		near(smoke.Lifetime.Min, 2, "Smoke lifetime min")
		near(smoke.Lifetime.Max, 3, "Smoke lifetime max")
		near(smoke.Speed.Min, 4, "Smoke speed min")
		near(smoke.Speed.Max, 8, "Smoke speed max")
		near(smoke.RotSpeed.Min, -30, "Smoke RotSpeed min")
		near(smoke.RotSpeed.Max, 30, "Smoke RotSpeed max")

		local outdoor, hangar = part:FindFirstChild("DustPuffOutdoor"), part:FindFirstChild("DustPuffHangar")
		expect(hex(outdoor.Color.Keypoints[1].Value) == "8c7b66" and hex(hangar.Color.Keypoints[1].Value) == "5a5e63", "dust colors")
		expect(outdoor.SpreadAngle == Vector2.new(80, 10) and outdoor:GetAttribute("EmitCount") == 14 and outdoor.Enabled == false, "dust puff is a 14-particle burst")
		near(outdoor.Size.Keypoints[2].Value, 6, "dust size end")
		near(outdoor.Lifetime.Max, 1.2, "dust lifetime max")
		near(outdoor.Speed.Min, 6, "dust speed min")

		local ash = part:FindFirstChild("AshFlakes")
		near(ash.Rate, 40, "Ash rate")
		near(ash.Lifetime.Min, 8, "Ash lifetime")
		near(ash.Speed.Max, 3, "Ash speed max")
		expect(ash.Acceleration == V3(2, -1.5, 0), "Ash drift")
		near(ash.Size.Keypoints[1].Value, 0.15, "Ash size")
		near(ash.Size.Keypoints[1].Envelope, 0.05, "Ash size varies 0.1 to 0.2")
		expect(hex(ash.Color.Keypoints[1].Value) == "9c9893", "Ash color")

		local regen = part:FindFirstChild("TitanRegen")
		near(regen.Rate, 6, "Regen rate")
		expect(regen.Enabled == false, "Regen starts disabled")
		near(regen.Size.Keypoints[2].Value, 3, "Regen size end")
		near(regen.Transparency.Keypoints[1].Value, 0.6, "Regen transparency start")

		fails(function()
			BK.emitter(part, "Confetti")
		end, "unknown preset")
	end)

	T.case("trigger prompt spawn cam nav barrier", function(f)
		local trigger = BK.trigger(f, "Trg", O + V3(-5, 0, -5), O + V3(5, 10, 5), "TRG_TEST")
		vec(trigger.Size, V3(10, 10, 10), "trigger size")
		expect(trigger.Transparency == 1 and not trigger.CanCollide and not trigger.CanQuery and trigger.CanTouch, "trigger flags")
		expect(trigger:HasTag("Trigger") and trigger:GetAttribute("TriggerId") == "TRG_TEST", "trigger tag and id")

		local desk = host(f, "Desk")
		local prompt = BK.prompt(desk, "INT_TEST", "Inspect")
		expect(prompt.ClassName == "ProximityPrompt" and prompt.Parent == desk and prompt.ActionText == "Inspect", "prompt")
		expect(prompt.HoldDuration == 0 and prompt.MaxActivationDistance == 8, "prompt defaults: hold 0, distance 8")
		expect(prompt.Style == Enum.ProximityPromptStyle.Custom and prompt.RequiresLineOfSight and prompt.Enabled, "custom style")
		expect(desk:HasTag("Interactable") and desk:GetAttribute("InteractId") == "INT_TEST", "Interactable tag and id")
		expect(desk:GetAttribute("FrameOnly") == false and desk:GetAttribute("OnFootOnly") == false and desk:GetAttribute("Once") == false, "context attributes")

		local housing = host(f, "Housing")
		local framePrompt = BK.prompt(housing, "INT_BREAKER_TEST", "Reset Breaker", { hold = 2, frameOnly = true, enabled = false, once = true })
		expect(framePrompt.HoldDuration == 2 and framePrompt.MaxActivationDistance == 70 and not framePrompt.RequiresLineOfSight, "Frame-scale prompt (distance 70, D-068)")
		expect(framePrompt.Enabled == false and housing:GetAttribute("FrameOnly") == true and housing:GetAttribute("Once") == true, "step-gated Frame prompt")
		fails(function()
			BK.prompt(host(f, "Both"), "INT_BOTH", "x", { frameOnly = true, onFootOnly = true })
		end, "frameOnly + onFootOnly")
		fails(function()
			BK.prompt(host(f, "NoId"), "", "x")
		end, "empty id")

		local spawnCFrame = CFrame.new(O + V3(-118, 0, 5)) * CFrame.Angles(0, math.rad(90), 0)
		local spawn = BK.spawnPoint(f, "SPAWN_TEST", spawnCFrame)
		expect(spawn.Name == "SPAWN_TEST" and spawn:HasTag("SpawnPoint") and spawn:GetAttribute("SpawnId") == "SPAWN_TEST", "spawn point")
		vec(spawn.Position, spawnCFrame.Position, "the spawn marker keeps the registry position")
		expect(spawn.CFrame.LookVector:Dot(spawnCFrame.LookVector) > 0.999, "the spawn marker keeps the facing")
		expect(spawn.Transparency == 1 and not spawn.CanCollide and not spawn.CanQuery, "spawn marker is invisible and soft")

		local camPos, camTarget = O + V3(8, 4, 70), O + V3(0, 3, 30)
		local cam = BK.camPoint(f, "CAM_TEST", camPos, camTarget)
		expect(cam:HasTag("CinematicCam") and cam:GetAttribute("CamId") == "CAM_TEST", "cam point")
		expect(cam.CFrame.LookVector:Dot((camTarget - camPos).Unit) > 0.999, "the cam point looks at its target")
		expect(cam:GetAttribute("LookAt") == camTarget, "LookAt attribute")
		local straightDown = BK.camPoint(f, "CAM_DOWN", O + V3(0, 50, 0), O)
		expect(straightDown.CFrame.LookVector:Dot(-Vector3.yAxis) > 0.999, "a cam point can look straight down")

		local nav = BK.navNode(f, "NAV_TEST", O + V3(0, 0, 20), { "NAV_A", "NAV_B" })
		expect(nav:HasTag("NavNode") and nav:GetAttribute("NavId") == "NAV_TEST" and nav:GetAttribute("Links") == "NAV_A,NAV_B", "nav node")

		local barrier = BK.barrier(f, "Barrier", O + V3(40, 0, -5), O + V3(42, 40, 5), "FrameBarrier")
		expect(barrier.CollisionGroup == "FrameBarrier" and barrier.Transparency == 1 and barrier.CanCollide and barrier.CanQuery, "barrier")
		expect(barrier:HasTag("NoCollideCamera") and not barrier.CastShadow, "barriers are ignored by cameras")
		vec(barrier.Size, V3(2, 40, 10), "barrier size")
		fails(function()
			BK.barrier(f, "BadGroup", O, O + V3(1, 1, 1), "Players")
		end, "unknown barrier group")
	end)

	T.case("dismountPad", function(f)
		local center = O + V3(0, 0, 30)
		local exit = CFrame.new(O + V3(16, 0, 24))
		local pad = BK.dismountPad(f, "PAD_A", center, 14, exit)
		expect(pad:IsA("Model") and pad.Name == "PAD_A" and pad:HasTag("DismountPad"), "pad model and tag")
		expect(pad:GetAttribute("PadId") == "PAD_A" and pad:GetAttribute("Radius") == 14 and pad:GetAttribute("Center") == center, "pad attributes")

		local ring, disc = pad:FindFirstChild("Ring"), pad:FindFirstChild("Disc")
		expect(ring.Shape == Enum.PartType.Cylinder and hex(ring.Color) == hex(P.HAZARD_YELLOW), "yellow ring")
		local rlo, rhi = T.bounds(ring)
		vec(rhi - rlo, V3(28, 0.2, 28), "ring diameter is 2 x radius")
		local dlo, dhi = T.bounds(disc)
		vec(dhi - dlo, V3(26, 0.22, 26), "concrete disc leaves a 1-stud ring")
		expect(dhi.Y > rhi.Y, "the disc sits just above the ring")
		expect(not ring.CanCollide and not disc.CanCollide and not ring.CanQuery, "pad visuals never collide")
		expect(pad.PrimaryPart == ring, "PrimaryPart is the ring")

		local label = pad:FindFirstChild("Label")
		expect(label and label:FindFirstChildOfClass("SurfaceGui"):FindFirstChildOfClass("TextLabel").Text == "PAD A", "floor text PAD A")
		local exitMarker = pad:FindFirstChild("ExitPoint")
		expect(exitMarker and exitMarker.Transparency == 1, "ExitPoint marker")
		vec(exitMarker.Position, exit.Position, "ExitPoint position")
		local stats = BK.stats(pad)
		expect(stats.lights == 4 and stats.shadowLights == 0, "4 edge lights without shadows")
		local lamp = pad:FindFirstChild("EdgeLight1")
		expect(lamp.Material == Enum.Material.Neon and hex(lamp.Color) == hex(BK.GLOW.amber.Color) and math.abs(lamp.Transparency - BK.GLOW.amber.Transparency) < 1e-4, "amber glow edge lights (D-099)")
		vec(lamp.Position, center + V3(0, 0.15, -13.5), "the first edge light is on the north edge")
	end)
end
